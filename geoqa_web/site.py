"""Build a self-contained web-GIS site from GeoQA findings."""

from __future__ import annotations

import json
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

from .charts import chart_bundle


def _utc_stamp() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")


def _escape(value: Any) -> str:
    import html

    return html.escape(str(value if value is not None else ""))


def _json_for_script(payload: Any) -> str:
    """Serialise JSON for embedding inside an inline <script> block.

    Dataset attributes are untrusted (OSM tags, arbitrary columns), so a literal
    ``</script>`` inside a description would otherwise close the script element
    and inject markup. Escaping the forward slash keeps the value intact as
    data while making it inert.
    """
    return (
        json.dumps(payload, separators=(",", ":"))
        .replace("</", "<\\/")
        .replace(" ", "\\u2028")
        .replace(" ", "\\u2029")
    )


def _collection(source: Any) -> dict[str, Any]:
    if isinstance(source, dict) and source.get("type") == "FeatureCollection":
        return source
    if hasattr(source, "to_geojson"):
        return source.to_geojson()
    if isinstance(source, (str, Path)):
        return json.loads(Path(source).read_text(encoding="utf-8"))
    if hasattr(source, "issues"):
        from geoqa.reports.geojson import issues_to_geojson

        return issues_to_geojson(source.issues)
    raise TypeError(f"Unsupported source for build_site: {type(source)!r}")


def _layer_payload(layers: dict[str, Any] | None) -> list[dict[str, Any]]:
    """Accept GeoJSON paths, dicts, or GeoDataFrames and emit inline data."""
    palette = ["#3b82f6", "#22c55e", "#a855f7", "#f97316", "#14b8a6", "#ec4899"]
    payload: list[dict[str, Any]] = []
    for index, (name, value) in enumerate((layers or {}).items()):
        if hasattr(value, "to_crs"):
            value = json.loads(value.to_crs("EPSG:4326").to_json())
        elif isinstance(value, (str, Path)):
            value = json.loads(Path(value).read_text(encoding="utf-8"))
        payload.append({
            "id": str(name),
            "name": str(name).replace("_", " ").title(),
            "color": palette[index % len(palette)],
            "data": value,
        })
    return payload


def build_site(
    source: Any,
    output_dir: str | Path,
    *,
    title: str = "GeoQA Findings",
    subtitle: str = "Spatial data quality report",
    base_layers: dict[str, Any] | None = None,
    storyboard: list[dict[str, Any]] | None = None,
    auto_play: bool = True,
) -> Path:
    """Write a static web-GIS site for the given findings.

    Args:
        source: A ``GeoQAReport``, GeoJSON path, FeatureCollection, or issues list.
        output_dir: Directory to create; ``index.html`` is written inside it.
        title: Heading shown in the site header.
        subtitle: Supporting line under the heading.
        base_layers: Optional reference layers rendered beneath the findings.
        storyboard: Optional camera/filter steps for the guided tour.
        auto_play: When False the tour waits for the viewer to start it.

    Returns:
        The path to the generated ``index.html``.
    """
    from . import _read_template

    collection = _collection(source)
    features = collection.get("features", [])

    from geoqa.reports.geojson import errors_summary

    summary = errors_summary(collection)
    unmapped = int((collection.get("geoqa") or {}).get("unmapped_count", 0))

    if storyboard is None:
        storyboard = _default_storyboard(features)
    if not auto_play:
        storyboard = []

    payload = {
        "findings": features,
        "base_layers": _layer_payload(base_layers),
        "auto_play": storyboard,
        "summary": summary,
        "unmapped": unmapped,
        "generated": _utc_stamp(),
    }

    page = _read_template("site.html")
    page = page.replace("__TITLE__", _escape(title))
    page = page.replace("__SUBTITLE__", _escape(subtitle))
    page = page.replace("__DESCRIPTION__", _escape(f"{subtitle} generated by GeoQA"))
    page = page.replace("__GENERATED__", _escape(_utc_stamp()))
    page = page.replace("__DATA__", _json_for_script(payload))

    target = Path(output_dir)
    target.mkdir(parents=True, exist_ok=True)
    index = target / "index.html"
    index.write_text(page, encoding="utf-8")

    # A standalone copy of the findings keeps the site analysable on its own.
    (target / "findings.geojson").write_text(json.dumps(collection), encoding="utf-8")
    (target / "summary.json").write_text(
        json.dumps({**summary, "unmapped": unmapped}, indent=2), encoding="utf-8"
    )
    return index


def _default_storyboard(features: list[dict[str, Any]]) -> list[dict[str, Any]]:
    steps: list[dict[str, Any]] = [{"severity": None, "fit": True, "hold": 2600}]
    for severity in ("critical", "high", "medium", "low"):
        if any(f.get("properties", {}).get("severity") == severity for f in features):
            steps.append({"severity": [severity], "fit": True, "hold": 2400})
    return steps


def build_full_package(
    source: Any,
    output_dir: str | Path,
    *,
    title: str = "GeoQA Findings",
    subtitle: str = "Spatial data quality report",
    base_layers: dict[str, Any] | None = None,
) -> dict[str, Path]:
    """Build the site, a slide deck, and the chart assets together."""
    from .slides import build_slides

    collection = _collection(source)
    target = Path(output_dir)
    return {
        "site": build_site(collection, target / "site", title=title, subtitle=subtitle, base_layers=base_layers),
        "slides": build_slides(collection, target / "slides", title=title, subtitle=subtitle),
        "charts": target / "charts.json",
    }


__all__ = ["build_full_package", "build_site"]